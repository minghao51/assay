#!/usr/bin/env node
/**
 * build-collector.mjs — build the ONE deployable artefact for the telemetry
 * collector, prove it runs standalone, and prove the LIVE endpoint answers.
 *
 * Usage
 *   node scripts/build-collector.mjs                  # build + offline proof; 0/1
 *   node scripts/build-collector.mjs --probe <url>    # probe a live endpoint; 0/1
 *   node scripts/build-collector.mjs --help           # usage; 0
 *   exit 2                                            # usage error
 *
 * Why this exists (ADR 0053; docs/engineering/07-telemetry-collector.md §5)
 * -----------------------------------------------------------------------
 * The collector source is `netlify/functions/collect.ts` and it imports the
 * schema from `@assay/telemetry` — one schema, no copy (ADR 0045). Netlify can
 * compile that TypeScript itself, but a **v2** function forces the `nft`
 * dependency tracer, `node_bundler = "esbuild"` is ignored, and nft leaves the
 * workspace specifier external: the shipped bundle keeps
 * `import … from "@assay/telemetry"` and carries only the `node_modules`
 * symlink plus `packages/telemetry/package.json`, whose `exports` points at
 * `src/index.ts`. Netlify does not ship that file, so a deploy that looks green
 * 502s on first invocation with `ERR_MODULE_NOT_FOUND`. (Proven by unzipping
 * the deployed function.)
 *
 * The fix is to stop asking Netlify to resolve anything: bundle the handler
 * here, with esbuild, into ONE self-contained file that inlines
 * `@assay/telemetry`, and point the functions directory at the output
 * (`netlify/dist`). nft then has nothing to trace — the file imports only
 * `node:` builtins — and the package's validator/allowlist/caps stay the single
 * source of truth because they are compiled in, never copied.
 *
 * ## The offline proof (default mode)
 *
 * The artefact is copied ALONE into a fresh temporary directory (so no
 * `node_modules` above it can satisfy a bare specifier) and imported there,
 * then driven through the contract's acceptance and refusal paths (§2, §2.2).
 * A green build therefore means "this exact file, these exact bytes, answers
 * correctly with no help from the repository".
 *
 * ## The live proof (`--probe <url>`)
 *
 * The SAME probes, over HTTP, against the deployed endpoint. This exists because
 * a green deploy job is not evidence the function works: the failure this file
 * was written for — a green deploy that 502s — is invisible to the deploy step
 * and visible here. A 502 is a failure of the bundling, not of the probe.
 */

/* global Request, fetch */
import { Buffer } from 'node:buffer'
import { createHash } from 'node:crypto'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import process from 'node:process'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL, URL } from 'node:url'

import { build } from 'esbuild'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = join(ROOT, 'netlify/functions/collect.ts')
/** The directory the Netlify functions setting points at: build output only. */
const OUT_DIR = join(ROOT, 'netlify/dist')
/** The single shipped function file. `.mjs` states the module type outright. */
const OUT_FILE = join(OUT_DIR, 'collect.mjs')
/** The valid-event builder the package's own tests use — never a local copy. */
const SCHEMA_HELPER = join(ROOT, 'packages/telemetry/src/test-support.ts')

const BANNER = [
  '// GENERATED by `pnpm collector:build` (scripts/build-collector.mjs).',
  '// Do not edit: edit netlify/functions/collect.ts and rebuild.',
  '// Self-contained by construction — `@assay/telemetry` is inlined, so Netlify',
  '// has no workspace specifier left to resolve (see the script header).',
].join('\n')

async function cli(argv) {
  const args = argv.slice(2)
  if (args.includes('--help') || args.includes('-h')) {
    out(
      [
        'Usage: node scripts/build-collector.mjs [--probe <endpoint-url>] [--help]',
        '',
        'Default: bundle netlify/functions/collect.ts into the self-contained',
        'netlify/dist/collect.mjs, import that exact file from a temporary directory',
        'with no node_modules reachable, and run the contract probes against it.',
        '',
        '--probe <url>: run the same probes over HTTP against a deployed endpoint,',
        'so a green deploy is confirmed by behaviour, not by exit status.',
      ].join('\n'),
    )
    return 0
  }

  const probeIndex = args.indexOf('--probe')
  const probeTarget = probeIndex === -1 ? undefined : args[probeIndex + 1]
  const known = new Set(['--probe', probeTarget ?? ''])
  const unknown = args.filter((arg) => !known.has(arg))
  if (unknown.length > 0 || (probeIndex !== -1 && probeTarget === undefined)) {
    err(
      `build-collector: bad arguments (${args.join(' ')}); usage: --probe <endpoint-url> | --help`,
    )
    return 2
  }

  try {
    if (probeTarget === undefined) await buildAndProve()
    else await probeLive(probeTarget)
    return 0
  } catch (error) {
    err(`\nbuild-collector: FAILED — ${error instanceof Error ? error.message : error}`)
    return 1
  }
}

// Importable by its own test (convention: `check-assurance-map.mjs` and
// `check-current-state.mjs` guard the same way). Nothing runs on import.
const invokedDirectly =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invokedDirectly) process.exitCode = await cli(process.argv)

// ---------------------------------------------------------------------------
// default mode: build the artefact, then prove it standalone
// ---------------------------------------------------------------------------

async function buildAndProve() {
  await buildArtefact()
  const text = await readFile(OUT_FILE, 'utf8')
  assertSelfContained(text)
  const module = await importStandalone(text)
  // Offline: `send` dispatches straight to the handler, so no socket is opened and
  // the host below is never dialled. It is a label, not a destination — the live
  // path passes the real URL (see `probeLive`).
  const probes = defineProbes(
    module,
    (request) => module.default(request),
    'https://collector.example.invalid/.netlify/functions/collect',
  )
  const failed = await runProbes(probes, 'netlify/dist/collect.mjs, imported from a temp dir')

  const digest = createHash('sha256').update(text, 'utf8').digest('hex')
  out(
    [
      '',
      `built  netlify/dist/collect.mjs  ${(Buffer.byteLength(text, 'utf8') / 1024).toFixed(1)} KiB  sha256 ${digest}`,
      '       self-contained: @assay/telemetry inlined, only node: builtins imported',
      `proved ${probes.length - failed}/${probes.length} probes against those exact bytes, imported`,
      '       with no node_modules reachable — they run with no help from the repo',
    ].join('\n'),
  )
}

/** Bundle the handler into one ESM file. No `external`: nothing may leak out. */
async function buildArtefact() {
  await build({
    entryPoints: [ENTRY],
    outfile: OUT_FILE,
    bundle: true,
    // `platform: node` keeps `node:` builtins external (the only imports a
    // correct bundle has) and picks Node's resolution for anything else.
    platform: 'node',
    format: 'esm',
    target: 'node24',
    // Deliberately NOT minified: the deployed file is ~13 KiB of already-
    // validated library code, and a readable artefact is reviewable in a stack
    // trace. Determinism comes from the pinned esbuild, not from size.
    minify: false,
    sourcemap: false,
    legalComments: 'none',
    banner: { js: BANNER },
    logLevel: 'warning',
  })
}

/**
 * The artefact must import nothing but `node:` builtins. This is the textual
 * half of the proof; the temp-directory import below is the behavioural half.
 */
function assertSelfContained(text) {
  const specifiers = new Set()
  const patterns = [
    // `import … from 'x'`, `export … from 'x'`
    /(?:^|\n)\s*(?:import|export)[^'"();]*?from\s*['"]([^'"]+)['"]/g,
    // side-effect `import 'x'`
    /(?:^|\n)\s*import\s*['"]([^'"]+)['"]/g,
    // dynamic `import('x')` and `require('x')`
    /\b(?:import|require)\s*\(\s*['"]([^'"]+)['"]\s*\)/g,
  ]
  for (const pattern of patterns) {
    for (const match of text.matchAll(pattern)) specifiers.add(match[1])
  }
  const external = [...specifiers].filter((specifier) => !specifier.startsWith('node:'))
  if (external.length > 0) {
    throw new Error(
      `the bundle still has non-builtin imports (${external.join(', ')}); ` +
        'esbuild must inline @assay/telemetry, not externalise it',
    )
  }
  if (/['"]@assay\//.test(text)) {
    throw new Error('the bundle still mentions an @assay/ specifier')
  }
}

/**
 * Copy the artefact ALONE into a fresh temporary directory and import it there.
 * Nothing resolves from the repository: if any bare specifier survived, this
 * import fails with ERR_MODULE_NOT_FOUND exactly as the deployed function did.
 */
async function importStandalone(text) {
  const dir = await mkdtemp(join(tmpdir(), 'assay-collector-'))
  const copy = join(dir, 'collect.mjs')
  await writeFile(copy, text, 'utf8')
  try {
    const module = await import(pathToFileURL(copy).href)
    if (typeof module.default !== 'function') {
      throw new Error('the bundle does not default-export a handler function')
    }
    return module
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
}

// ---------------------------------------------------------------------------
// --probe mode: the same probes, over HTTP
// ---------------------------------------------------------------------------

/**
 * Refuse a request that is addressed anywhere but `endpoint`.
 *
 * This is the regression guard for the 2026-11-27 defect: `--probe` reported
 * "fetch failed" eight times because the probes still carried the placeholder
 * host. A wrong target must name itself, not masquerade as an unhealthy endpoint.
 */
export function guardTarget(request, endpoint) {
  if (request.url !== endpoint) {
    throw new Error(
      `probe request targets ${request.url} but the deployment under test is ${endpoint}`,
    )
  }
  return request
}

async function probeLive(endpoint) {
  let parsed
  try {
    parsed = new URL(endpoint)
  } catch {
    throw new Error(`--probe needs an absolute URL, got ${JSON.stringify(endpoint)}`)
  }
  if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
    throw new Error(`--probe needs an http(s) URL, got ${parsed.protocol}`)
  }
  const target = `${parsed.origin}${parsed.pathname}`
  // The caps the probes use come from the built artefact (the same file the
  // deploy ships), never from a number retyped here.
  const text = await readFile(OUT_FILE, 'utf8')
  const module = await importStandalone(text)
  const probes = defineProbes(module, (request) => fetch(guardTarget(request, target)), target)
  const failed = await runProbes(probes, `the live endpoint ${target}`)
  out(
    [
      '',
      `probed ${target}`,
      `       ${probes.length - failed}/${probes.length} green over HTTP — a 502 here means the`,
      '       bundling failed, not the probe',
    ].join('\n'),
  )
}

// ---------------------------------------------------------------------------
// the contract probes: one definition, both transports
// ---------------------------------------------------------------------------

/**
 * The contract's own acceptance list (docs/engineering/07-telemetry-collector.md
 * §2, §2.2). Each probe asserts the status AND the closed reason code, so a
 * handler that accepted everything would fail here. `send` and `endpoint` are the
 * only differences between the offline and live runs.
 *
 * `endpoint` is REQUIRED and must be the URL the requests are actually addressed
 * to. It used to be a hardcoded `.invalid` placeholder with `--probe` passing
 * `fetch` straight through, so the live probe dialled
 * `https://collector.example.invalid/…` on every run: 8/8 "fetch failed" and a red
 * step against ANY endpoint, healthy or not (found 2026-11-27). The guard in
 * `guardTarget` now makes that failure loud and named instead of silent.
 */
export function defineProbes(module, send, endpoint) {
  const { MAX_REQUEST_BYTES } = module
  if (typeof MAX_REQUEST_BYTES !== 'number' || MAX_REQUEST_BYTES <= 0) {
    throw new Error('the bundle does not export MAX_REQUEST_BYTES')
  }
  if (typeof endpoint !== 'string' || endpoint === '') {
    throw new Error('defineProbes needs the endpoint its requests are addressed to')
  }
  const post = (body, headers = {}) =>
    send(
      new Request(endpoint, {
        method: 'POST',
        headers: { 'content-type': 'application/json', ...headers },
        body,
      }),
    )

  let event
  const probes = []
  const check = (name, fn) => probes.push({ name, fn })

  check('POST a valid event array → 202 {"ok":true}', async () => {
    event = await validEvent()
    const response = await post(JSON.stringify([event]))
    expect(response.status, 202)
    expect(await response.text(), '{"ok":true}')
  })

  check('POST again (a second request, same warm instance) → 202', async () => {
    const response = await post(JSON.stringify([event, event]))
    expect(response.status, 202)
    expect(await response.text(), '{"ok":true}')
  })

  check('POST an unknown field → 400 invalid-event, nothing echoed', async () => {
    const canary = 'ssn-4111-1111-1111-1111'
    const response = await post(JSON.stringify([{ ...event, ssn: canary }]))
    expect(response.status, 400)
    const body = await response.text()
    if (body.includes(canary)) throw new Error('the refusal echoed a request value')
    expect(body.includes('"invalid-event"'), true)
  })

  check('GET → 405 with Allow, closed code', async () => {
    const response = await send(new Request(endpoint))
    expect(response.status, 405)
    expect(response.headers.get('allow'), 'POST, OPTIONS')
    expect((await response.text()).includes('"method-not-allowed"'), true)
  })

  check('OPTIONS → 204 (same-origin preflight needs no grant)', async () => {
    const response = await send(new Request(endpoint, { method: 'OPTIONS' }))
    expect(response.status, 204)
  })

  check('POST text/plain → 415 unsupported-media-type', async () => {
    const response = await post('hello', { 'content-type': 'text/plain' })
    expect(response.status, 415)
    expect((await response.text()).includes('"unsupported-media-type"'), true)
  })

  check('POST one byte over the body cap → 413 body-too-large', async () => {
    const response = await post('[' + '0'.repeat(MAX_REQUEST_BYTES) + ']')
    expect(response.status, 413)
    expect((await response.text()).includes('"body-too-large"'), true)
  })

  check('POST malformed JSON → 400 malformed-json', async () => {
    const response = await post('{"not":"an array"')
    expect(response.status, 400)
    expect((await response.text()).includes('"malformed-json"'), true)
  })

  return probes
}

/** A valid event built from the package's descriptor, by the package's helper. */
async function validEvent() {
  const bundled = await build({
    entryPoints: [SCHEMA_HELPER],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'node',
    logLevel: 'silent',
  })
  const source = bundled.outputFiles?.[0]?.text
  if (source === undefined) throw new Error('could not bundle the valid-event helper')
  const helper = await import(
    `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`
  )
  const event = helper.validEventFor('app_boot')
  if (typeof event !== 'object' || event === null) {
    throw new Error('the valid-event helper returned no event')
  }
  return event
}

async function runProbes(probes, what) {
  out(`probing ${what}`)
  // The handler logs every refusal (value-free, by design — `collect.test.ts`
  // pins it). Silence it here: this run's output is the probe table below, and
  // a wall of expected refusals would bury a real failure. The handler in the
  // live case runs inside Netlify, so silencing is a no-op there — harmless.
  const realConsole = globalThis.console
  const quiet = { ...realConsole, warn: () => {}, error: () => {} }
  globalThis.console = quiet
  let failed = 0
  try {
    for (const probe of probes) {
      try {
        await probe.fn()
        out(`  ok    ${probe.name}`)
      } catch (cause) {
        failed += 1
        out(`  FAIL  ${probe.name}`)
        out(`        ${cause instanceof Error ? cause.message : cause}`)
      }
    }
  } finally {
    globalThis.console = realConsole
  }
  if (failed > 0) throw new Error(`${failed} of ${probes.length} probes failed against ${what}`)
  return failed
}

/** A line on stdout. Scripts here write through `process`, never `console`. */
function out(line = '') {
  process.stdout.write(`${line}\n`)
}

/** A line on stderr. */
function err(line = '') {
  process.stderr.write(`${line}\n`)
}

function expect(actual, expected) {
  if (actual !== expected) {
    throw new Error(`expected ${JSON.stringify(expected)}, got ${JSON.stringify(actual)}`)
  }
}
