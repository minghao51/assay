import path from 'node:path'
import { expect, test } from './support/fixture'
import type { Page } from '@playwright/test'
import { cell, row, waitForReadyRow } from './support/grid'

/**
 * wf-01 (WFD-06 = B) end-to-end pin against the **real engine**.
 *
 * The read-only WF-01P probe measured that no temporal payload is ever a JS
 * `Date`: `DATE`/`TIMESTAMP*` cross as epoch-**millisecond** numbers (fractional
 * when the column carries µs) and `TIME` as a **bigint of microseconds since
 * midnight**. Before this row the grid rendered those raw numbers
 * (`1709164800000`, `1709214312123.456`, `49512123456`) because `formatCell`'s
 * only temporal branch was `value instanceof Date`. This spec opens the
 * committed `fixtures/parquet/temporal.parquet` fixture (the first fixture with
 * declared temporal types) and pins:
 *
 * 1. the approved display text per family and per fraction width, including a
 *    pre-1970 sub-millisecond instants (never snapped onto the epoch);
 * 2. the raw-number fallback for the lossy `TIMESTAMP_NS` delivery;
 * 3. that the focused display-value copy is byte-identical to the cell text;
 * 4. that display never leaks into storage: the Record tree (no declared-type
 *    channel — the WF-O2 residual) still shows the raw payload, and the inline
 *    editor keeps its unchanged ms-only draft.
 *
 * The fixture (4 rows, generated by `fixtures/parquet/generate.sh`):
 *
 *   d (DATE)     ts (TIMESTAMP)               ts_ns (TIMESTAMP_NS)               t (TIME)
 *   2024-02-29   2024-02-29 13:45:12.123456   2024-02-29 13:45:12.123456789      13:45:12.123456
 *   1969-12-31   1969-12-31 23:59:59.999999   1969-12-31 23:59:59.999999999      23:59:59.999999
 *   1970-01-01   2024-02-29 00:00:00          2024-02-29 13:45:12.123             00:00:00
 *   NULL         NULL                         NULL                               NULL
 *
 * Picker path: as in the other web specs, the FSA global is removed so the
 * hidden-input fallback drives Playwright's filechooser.
 */

const TEMPORAL_FIXTURE = path.join(process.cwd(), 'fixtures', 'parquet', 'temporal.parquet')

/** Column indexes in the fixture's declared order. */
const COL_DATE = 0
const COL_TS = 1
const COL_TS_NS = 2
const COL_TIME = 3

/** Read the browser clipboard (permissions are granted for this file). */
function readClipboard(page: Page): Promise<string> {
  return page.evaluate(() => navigator.clipboard.readText())
}

test.use({ permissions: ['clipboard-read', 'clipboard-write'] })

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    try {
      delete (window as { showOpenFilePicker?: unknown }).showOpenFilePicker
    } catch {
      // Non-configurable global: the chooser assertion fails loudly instead.
    }
  })
})

async function openTemporal(page: Page): Promise<void> {
  await page.goto('/')
  const chooserPromise = page.waitForEvent('filechooser')
  await page.getByTestId('open-button').click()
  const chooser = await chooserPromise
  await chooser.setFiles(TEMPORAL_FIXTURE)
  await expect(page.getByTestId('open-status')).toHaveAttribute('data-phase', 'ready', {
    timeout: 20_000,
  })
  await expect(page.getByTestId('grid-total-rows')).toHaveText('4')
}

test('typed temporal cells render UTC ISO-like text at the delivered precision', async ({
  page,
}) => {
  await openTemporal(page)

  // The declared types reach the grid — this is how `formatCell` knows the
  // family at all (an untyped SQL result must stay raw).
  await expect(page.locator('[data-testid="grid-header-cell"][data-col-name="d"]')).toHaveAttribute(
    'data-col-type',
    'DATE',
  )
  await expect(
    page.locator('[data-testid="grid-header-cell"][data-col-name="ts"]'),
  ).toHaveAttribute('data-col-type', 'TIMESTAMP')
  await expect(
    page.locator('[data-testid="grid-header-cell"][data-col-name="ts_ns"]'),
  ).toHaveAttribute('data-col-type', 'TIMESTAMP_NS')
  await expect(page.locator('[data-testid="grid-header-cell"][data-col-name="t"]')).toHaveAttribute(
    'data-col-type',
    'TIME',
  )

  // Row 0 — leap day, microseconds in both the timestamp and the time.
  await waitForReadyRow(page, 0)
  await expect(cell(page, 0, COL_DATE)).toHaveText('2024-02-29')
  await expect(cell(page, 0, COL_TS)).toHaveText('2024-02-29T13:45:12.123456Z')
  await expect(cell(page, 0, COL_TIME)).toHaveText('13:45:12.123456')

  // Row 1 — pre-1970 sub-millisecond: the exact instant, never snapped to
  // `1970-01-01T00:00:00.000Z` (the rejected fractional-`new Date` decode).
  await waitForReadyRow(page, 1)
  await expect(cell(page, 1, COL_DATE)).toHaveText('1969-12-31')
  await expect(cell(page, 1, COL_TS)).toHaveText('1969-12-31T23:59:59.999999Z')
  await expect(cell(page, 1, COL_TIME)).toHaveText('23:59:59.999999')

  // Row 2 — midnight/whole second (no fraction at all), and a millisecond-exact
  // TIMESTAMP_NS value: the fraction WIDTH follows the VALUE, not the column
  // type, so the ns column renders `.123Z` here while row 0's ns payload stays
  // raw (next test).
  await waitForReadyRow(page, 2)
  await expect(cell(page, 2, COL_DATE)).toHaveText('1970-01-01')
  await expect(cell(page, 2, COL_TS)).toHaveText('2024-02-29T00:00:00Z')
  await expect(cell(page, 2, COL_TS_NS)).toHaveText('2024-02-29T13:45:12.123Z')
  await expect(cell(page, 2, COL_TIME)).toHaveText('00:00:00')

  // Row 3 — NULL stays a NULL affordance, not an empty or fabricated instant.
  await waitForReadyRow(page, 3)
  for (const column of [COL_DATE, COL_TS, COL_TS_NS, COL_TIME]) {
    await expect(cell(page, 3, column).getByTestId('grid-cell-null')).toBeVisible()
  }
})

test('the lossy TIMESTAMP_NS delivery keeps its raw number, never a truncated instant', async ({
  page,
}) => {
  await openTemporal(page)
  await waitForReadyRow(page, 0)

  // `…12.123456789` arrives as `1709214312123.4568` ms: `ms * 1000` is not
  // integral, so the delivered precision is NOT recoverable and the approved
  // fallback is the raw delivered number (approval record §9) — no rounding to
  // `.123457Z`, no silent truncation to `.123Z`.
  const nsCell = cell(page, 0, COL_TS_NS)
  await expect(nsCell).toHaveText(/^1709214312123\.\d+$/)
  await expect(nsCell).not.toContainText('T')

  // The pre-1970 ns payload is equally unreadable exactly and stays raw.
  await waitForReadyRow(page, 1)
  await expect(cell(page, 1, COL_TS_NS)).toHaveText(/^-0\.0+\d+$/)
})

test('the focused display-value copy is byte-identical to the rendered cell', async ({ page }) => {
  await openTemporal(page)
  await waitForReadyRow(page, 0)

  const live = page.getByTestId('edit-live-region')

  // A microsecond timestamp copies the six-digit display text, not the raw
  // epoch-ms number the engine delivered.
  const tsCell = cell(page, 0, COL_TS)
  await expect(tsCell).toHaveText('2024-02-29T13:45:12.123456Z')
  await tsCell.focus()
  await page.keyboard.press('Control+C')
  await expect(live).toHaveText('Value copied.')
  await expect.poll(() => readClipboard(page)).toBe('2024-02-29T13:45:12.123456Z')

  // A TIME cell copies its wall clock, and the raw fallback copies its raw
  // number — display and copy can never diverge (both compose through
  // `formatCell`).
  const timeCell = cell(page, 0, COL_TIME)
  await expect(timeCell).toHaveText('13:45:12.123456')
  await timeCell.focus()
  await page.keyboard.press('Control+C')
  await expect.poll(() => readClipboard(page)).toBe('13:45:12.123456')

  const nsText = (await cell(page, 0, COL_TS_NS).innerText()).trim()
  await cell(page, 0, COL_TS_NS).focus()
  await page.keyboard.press('Control+C')
  await expect.poll(() => readClipboard(page)).toBe(nsText)

  // A NULL temporal cell has nothing to copy and says so (value-free).
  await waitForReadyRow(page, 3)
  await cell(page, 3, COL_TS).focus()
  await page.keyboard.press('Control+C')
  await expect(live).toHaveText('Nothing to copy — this cell is empty.')
})

test('display is presentation only: raw storage and the editor draft are untouched', async ({
  page,
}) => {
  await openTemporal(page)
  await waitForReadyRow(page, 0)

  // The Record tree has no declared-type channel (WF-O2, out of scope), so it
  // shows the RAW payload — proof the formatted string never entered storage.
  await row(page, 0).click()
  const record = page.getByTestId('record-inspector')
  await expect(record).toBeVisible()
  await expect(record).toHaveAttribute('data-row-index', '0')
  await expect(record).toContainText('1709214312123.456')
  await expect(record).not.toContainText('2024-02-29T13:45:12.123456Z')

  // The inline editor keeps its byte-identical ms-only draft (approval record
  // §9: display and editor draft are ALLOWED to differ for sub-millisecond
  // cells; changing it is not authorized by this row).
  await cell(page, 0, COL_TS).dblclick()
  const editor = page.getByTestId('grid-editor-input')
  await expect(editor).toHaveValue('2024-02-29T13:45:12.123Z')
  // Escape cancels: no staged edit, no undo step, the cell is unchanged.
  await editor.press('Escape')
  await expect(page.getByTestId('grid-cell-editor')).toHaveCount(0)
  await expect(page.getByTestId('pending-changes')).toHaveText('No pending changes.')
  await expect(cell(page, 0, COL_TS)).toHaveAttribute('data-dirty', 'false')
  await expect(cell(page, 0, COL_TS)).toHaveText('2024-02-29T13:45:12.123456Z')
})
