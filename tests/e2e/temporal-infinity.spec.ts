import path from 'node:path'
import { expect, test } from './support/fixture'
import type { Page } from '@playwright/test'
import { cell, waitForReadyRow } from './support/grid'

/**
 * R2 (D6, projection-boundary guard) end-to-end pin against the **real engine**.
 *
 * DuckDB encodes `TIMESTAMP 'infinity'` / `'-infinity'` as the two int64
 * extremes, and Arrow's `get()` throws on those bits for the SECOND /
 * MILLISECOND / MICROSECOND units (`bigIntToNumber`'s safety check) *before*
 * any formatter runs — one infinite timestamp used to throw away the whole
 * delivered window/page (probe 2026-11-14). The projection guard now reads
 * the exact raw `BigInt64Array` for those units and emits DuckDB's own
 * sentinel text for the two extremes; every other cell keeps the untouched
 * `get()` path, so finite rendering stays byte-identical (WF-01 WFD-06 = B).
 *
 * The committed `fixtures/parquet/temporal-infinity.parquet` fixture (4 rows,
 * generated by `fixtures/parquet/generate.sh`) delivers, through the real
 * engine (DuckDB-WASM → Arrow 17):
 *
 *   ts (TIMESTAMP µs)      ts_ns (TIMESTAMP_NS)                label
 *   2400-01-01 00:00:00    2262-04-10 00:00:00.123456789       finite-late
 *   infinity               infinity (ns sentinel: no throw!)   infinity
 *   -infinity              1969-12-31 23:59:59.999999999       -infinity
 *   2024-02-29 13:45:12.123456   2024-02-29 13:45:12.123456789 finite-early
 *
 * Pins:
 * 1. the base path renders `infinity` / `-infinity` for the sentinels while
 *    the finite controls stay ISO-like text (a finite value near the extremes
 *    is never mislabelled);
 * 2. an overlay window (sorted view → `projectOverlayPage`) renders the same;
 * 3. `TIMESTAMP_NS` stays entirely on today's raw path — the ns sentinel does
 *    NOT throw and must show its lossy raw number, never the sentinel text.
 */

const FIXTURE = path.join(process.cwd(), 'fixtures', 'parquet', 'temporal-infinity.parquet')

/** Column indexes in the fixture's declared order. */
const COL_TS = 0
const COL_TS_NS = 1
const COL_LABEL = 2

/** Natural fixture order (base path): label per row index. */
const NATURAL_LABELS = ['finite-late', 'infinity', '-infinity', 'finite-early']
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    try {
      delete (window as { showOpenFilePicker?: unknown }).showOpenFilePicker
    } catch {
      // Non-configurable global: the chooser assertion fails loudly instead.
    }
  })
})

async function openInfinityFixture(page: Page): Promise<void> {
  await page.goto('/')
  const chooserPromise = page.waitForEvent('filechooser')
  await page.getByTestId('open-button').click()
  const chooser = await chooserPromise
  await chooser.setFiles(FIXTURE)
  await expect(page.getByTestId('open-status')).toHaveAttribute('data-phase', 'ready', {
    timeout: 20_000,
  })
  await expect(page.getByTestId('grid-total-rows')).toHaveText('4')
}

test('±infinity sentinels render as text on the base path; finite controls stay byte-identical', async ({
  page,
}) => {
  await openInfinityFixture(page)

  // The declared types reach the grid — the µs column is the throwing family
  // the guard covers; the ns column is declared TIMESTAMP_NS.
  await expect(
    page.locator('[data-testid="grid-header-cell"][data-col-name="ts"]'),
  ).toHaveAttribute('data-col-type', 'TIMESTAMP')
  await expect(
    page.locator('[data-testid="grid-header-cell"][data-col-name="ts_ns"]'),
  ).toHaveAttribute('data-col-type', 'TIMESTAMP_NS')

  // Row 0 — finite µs timestamps (negative control): ISO-like text at the
  // delivered precision, never mislabelled as infinity even though the raw
  // values sit in the same int64 neighbourhood as the sentinels.
  await waitForReadyRow(page, 0)
  await expect(cell(page, 0, COL_TS)).toHaveText('2400-01-01T00:00:00Z')
  await expect(cell(page, 0, COL_TS_NS)).toHaveText(/^9223200000123\.\d+$/)

  // Row 1 — TIMESTAMP 'infinity': DuckDB's own sentinel text, and the whole
  // window still renders (before the guard this row threw away the page).
  await waitForReadyRow(page, 1)
  await expect(cell(page, 1, COL_TS)).toHaveText('infinity')
  // Row 2 — TIMESTAMP '-infinity': same, with the exact signed text.
  await waitForReadyRow(page, 2)
  await expect(cell(page, 2, COL_TS)).toHaveText('-infinity')

  // Row 3 — a finite µs instant with a fraction: byte-identical to the
  // pre-guard rendering (WF-01 delivered-precision rule).
  await waitForReadyRow(page, 3)
  await expect(cell(page, 3, COL_TS)).toHaveText('2024-02-29T13:45:12.123456Z')

  // The labels anchor the row order on the base path (natural order).
  for (const [index, label] of NATURAL_LABELS.entries()) {
    await expect(cell(page, index, COL_LABEL)).toHaveText(label)
  }
})

test('the sorted overlay window renders the same sentinels (projectOverlayPage)', async ({
  page,
}) => {
  await openInfinityFixture(page)

  // Sorting forces the composed overlay path: every cell below is projected
  // through `projectOverlayPage` (with the engine's `assay_row_id` column
  // stripped into the key channel), not the base fast path.
  await page.locator('[data-testid="grid-sort-toggle"][data-col-name="label"]').click()
  await expect(
    page.locator('[data-testid="grid-sort-toggle"][data-col-name="label"]'),
  ).toHaveAttribute('data-sort', 'asc')

  // String order: '-infinity' < 'finite-early' < 'finite-late' < 'infinity'.
  const sorted = ['-infinity', 'finite-early', 'finite-late', 'infinity']
  for (const [index, label] of sorted.entries()) {
    await waitForReadyRow(page, index)
    await expect(cell(page, index, COL_LABEL)).toHaveText(label)
  }

  // Both sentinels survive the composed path with their exact text…
  await expect(cell(page, 0, COL_TS)).toHaveText('-infinity')
  await expect(cell(page, 3, COL_TS)).toHaveText('infinity')
  // …and the finite controls keep the byte-identical ISO-like rendering.
  await expect(cell(page, 1, COL_TS)).toHaveText('2024-02-29T13:45:12.123456Z')
  await expect(cell(page, 2, COL_TS)).toHaveText('2400-01-01T00:00:00Z')
})

test('TIMESTAMP_NS stays raw for every row — including an infinity payload', async ({ page }) => {
  await openInfinityFixture(page)
  await waitForReadyRow(page, 0)

  // An ns column has no display family (WF-01): every cell keeps the raw
  // delivered number. The ns SENTINEL row proves it does not throw and is
  // not diverted to the sentinel text — the lossy ms fold (9223372036854.775)
  // is exactly what the plain accessor returns for the ns int64 extreme.
  await expect(cell(page, 1, COL_TS_NS)).toHaveText('9223372036854.775')
  await expect(cell(page, 1, COL_TS_NS)).not.toContainText('infinity')

  // Finite ns cells equally stay raw, pre-1970 negative values included.
  await expect(cell(page, 0, COL_TS_NS)).toHaveText(/^9223200000123\.\d+$/)
  await expect(cell(page, 2, COL_TS_NS)).toHaveText(/^-0\.0+\d+$/)
  await expect(cell(page, 3, COL_TS_NS)).toHaveText(/^1709214312123\.\d+$/)

  // The ns column is never mislabelled on the overlay path either.
  await page.locator('[data-testid="grid-sort-toggle"][data-col-name="label"]').click()
  await waitForReadyRow(page, 0)
  for (const index of [0, 1, 2, 3]) {
    await expect(cell(page, index, COL_TS_NS)).not.toContainText('infinity')
    await expect(cell(page, index, COL_TS_NS)).not.toContainText('T')
  }
})
